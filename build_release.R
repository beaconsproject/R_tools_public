# build_release.R
# Combines the one-function-per-file scripts in R/ into category scripts
# (builder.R, hydrology.R, names.R, ranking.R, representation.R, spatial.R, utils.R)
# for sharing. Each function's category comes from the "Script" column of
# functions_list.csv.
#
# Run from the beacons_fct folder:  source("build_release.R")

fct_dir     <- "R"
release_dir <- "release"
list_file   <- "functions_list.csv"

if (!file.exists(list_file) || !dir.exists(fct_dir)) {
  stop("Run this script from the R_tools_public folder (working directory = beacons_fct).")
}

# ---- Read function list --------------------------------------------------
# The Script column is the category: one release script per unique value.
fl <- read.csv(list_file, stringsAsFactors = FALSE, check.names = FALSE,
               fileEncoding = "UTF-8-BOM")
fl$Functions <- trimws(fl$Functions)
fl$category  <- trimws(fl$Script)
# Only functions marked "done" in the R_tools_public column are released
fl <- fl[trimws(fl$R_tools_public) %in% "done", c("Functions", "category")]

no_category <- fl$Functions[fl$category == ""]
if (length(no_category)) {
  stop("Function(s) marked done but with an empty Script column: ",
       paste(no_category, collapse = ", "))
}

dups <- unique(fl$Functions[duplicated(fl$Functions)])
if (length(dups)) {
  stop("Function(s) listed more than once in ", list_file, ": ",
       paste(dups, collapse = ", "))
}

# ---- Match against function files ---------------------------------------
fct_files <- sub("[.]R$", "", list.files(fct_dir, pattern = "[.]R$"))

not_done <- setdiff(fct_files, fl$Functions)
if (length(not_done)) {
  message("In ", fct_dir, "/ but not marked done in ", list_file,
          " (not released): ", paste(not_done, collapse = ", "))
}

missing_files <- setdiff(fl$Functions, fct_files)
if (length(missing_files)) {
  message("Listed in ", list_file, " but no file in ", fct_dir, "/ (skipped): ",
          paste(missing_files, collapse = ", "))
}
fl <- fl[fl$Functions %in% fct_files, ]

# ---- Write category scripts ---------------------------------------------
# Delete and recreate release/ so a function that changed category
# never stays behind in its old script
unlink(release_dir, recursive = TRUE)
if (dir.exists(release_dir)) {
  stop("Could not delete ", release_dir, "/. Close any file open from it and rerun.")
}
dir.create(release_dir)

categories <- sort(unique(fl$category))
for (cat_name in categories) {
  fcts <- fl$Functions[fl$category == cat_name]
  body <- unlist(lapply(fcts, function(f) {
    c(readLines(file.path(fct_dir, paste0(f, ".R")), warn = FALSE), "", "")
  }))
  header <- c(
    paste0("# BEACONs R functions - ", cat_name),
    paste0("# Generated by build_release.R on ", Sys.Date(),
           ". Do not edit: change the files in beacons_fct/R/ instead."),
    paste0("# Functions: ", paste(fcts, collapse = ", ")),
    "", ""
  )
  writeLines(c(header, body), file.path(release_dir, paste0(cat_name, ".R")))
  message(sprintf("%-15s %2d functions", paste0(cat_name, ".R"), length(fcts)))
}

# ---- Loader for users ---------------------------------------------------
writeLines(c(
  "# Load all BEACONs R functions.",
  "# Usage: source(\"path/to/release/load_all.R\", chdir = TRUE)",
  "",
  sprintf("source(\"%s.R\")", categories)
), file.path(release_dir, "load_all.R"))

message("Release written to ", normalizePath(release_dir))
